<?php
/**
 * Analytics Export Module
 * Handles CSV and PDF exports for analytics data
 * (PDF requires external library installation)
 */

// Start output buffering to prevent "headers already sent" errors
ob_start();

session_start();

// Check if user is logged in
if (!isset($_SESSION['username'])) {
    header("Location: /index.php");  
    exit();
}

require_once __DIR__ . '/includes/db_connection.php';
require_once __DIR__ . '/includes/analytics_filters.php';

// PDF Library - TCPDF (includes will define constants)
require_once __DIR__ . '/includes/dependencies.php';

// Shared filters (synced across analytics pages)
$filterState = analytics_get_filter_state($conn);
$selected_year = $_GET['year'] ?? $filterState['selected_year'] ?? 'all';
$selected_semester = $_GET['semester'] ?? $filterState['selected_semester'] ?? 'all';

// Normalize semester to ensure proper type comparison (integer 1/2 or string 'all')
if ($selected_semester !== 'all') {
    $selected_semester = (int)$selected_semester;
    if ($selected_semester !== 1 && $selected_semester !== 2) {
        $selected_semester = 'all';
    }
}

$erCond = analytics_build_er_condition($conn, $selected_year, $selected_semester, 'e');
$sy_cond = $erCond['sql'];
$school_year_label = $erCond['label_year'];
$semester_label = $erCond['label_semester'];

$report_type = $_GET['report'] ?? 'summary';

// If user selected a specific semester, validate it has data
// (Don't force it back to 'all' unless truly necessary)
if ($selected_semester !== 'all') {
    $conds = [];
    
    if ($selected_year !== 'all') {
        $yearEsc = $conn->real_escape_string($selected_year);
        $conds[] = "REPLACE(REPLACE(e.school_year, '–', '-'), '—', '-') = '$yearEsc'";
    }
    
    $semInt = (int)$selected_semester;
    $conds[] = "e.semester = $semInt";
    
    $whereSql = implode(' AND ', $conds);
    $hasDataSql = "SELECT 1 FROM evaluations e WHERE $whereSql LIMIT 1";
    $hasDataRes = $conn->query($hasDataSql);
    
    // Only reset if there's truly no data for the selected semester
    if (!$hasDataRes || $hasDataRes->num_rows === 0) {
        $selected_semester = 'all';
    }
}

// ============================================
// EXPORT: Summary Report (PDF Format)
// ============================================
if ($report_type === 'summary_pdf') {
    app_require_dependencies();
    ob_end_clean();
    $summary = generate_summary_data($conn, $sy_cond, $school_year_label, $semester_label, $selected_year);
    $pdf = generate_pdf_report($summary, $_SESSION['username']);
    
    // Output PDF
    $pdfSlug = analytics_export_csv_slug($selected_year, $selected_semester);
    $pdf->Output('faculty_evaluation_summary_' . $pdfSlug . '_' . date('Y-m-d') . '.pdf', 'D');
    exit;
}

// ============================================
// HELPERS: CSV export (BOM, metadata, filenames)
// ============================================
function analytics_export_csv_slug($selected_year, $selected_semester): string {
    if ($selected_year === 'all') {
        $y = 'AllYears';
    } else {
        $y = preg_replace('/[^a-zA-Z0-9._-]+/', '_', analytics_normalize_school_year((string) $selected_year));
    }
    if ($selected_semester === 'all') {
        $s = 'AllSem';
    } else {
        $s = 'S' . (int) $selected_semester;
    }
    return $y . '_' . $s;
}

function analytics_export_csv_meta_rows(string $school_year_label, string $semester_label, string $username): array {
    return [
        '# Report filters',
        '# School Year: ' . $school_year_label,
        '# Semester: ' . $semester_label,
        '# Generated: ' . date('Y-m-d H:i:s'),
        '# Generated by: ' . $username,
    ];
}

/** Numeric DB value for CSV; empty cell when NULL (e.g. STDDEV with one row). */
function analytics_csv_numeric($val, int $decimals = 2) {
    if ($val === null || $val === '') {
        return '';
    }
    return round((float) $val, $decimals);
}

/**
 * Opens CSV download with UTF-8 BOM and optional # metadata lines (Excel-friendly).
 */
function analytics_csv_open_download(string $filename, array $meta_rows = []) {
    header('Content-Type: text/csv; charset=utf-8');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    $out = fopen('php://output', 'w');
    fwrite($out, "\xEF\xBB\xBF");
    foreach ($meta_rows as $line) {
        fputcsv($out, [$line]);
    }
    if (!empty($meta_rows)) {
        fputcsv($out, []);
    }
    return $out;
}

/**
 * Stream mysqli result rows to CSV and close handle.
 */
function analytics_export_csv_from_query(
    mysqli $conn,
    string $sql,
    string $filename,
    array $meta_rows,
    array $column_headers,
    callable $map_row
): void {
    $out = analytics_csv_open_download($filename, $meta_rows);
    fputcsv($out, $column_headers);
    $result = $conn->query($sql);
    if ($result && $result->num_rows > 0) {
        while ($row = $result->fetch_assoc()) {
            fputcsv($out, $map_row($row));
        }
    }
    fclose($out);
}

