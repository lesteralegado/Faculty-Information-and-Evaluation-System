// HELPER: Generate Summary Report Data
// ============================================
function generate_summary_data($conn, $sy_cond, $school_year_label, $semester_label, $selected_year) {
    $summary = [];
    
    // Overall Statistics - matching data_analytics.php logic
    $total_eval = $conn->query("SELECT COUNT(DISTINCT e.evaluation_id) as cnt FROM evaluation_responses er JOIN evaluations e ON er.evaluation_id = e.evaluation_id WHERE $sy_cond")->fetch_assoc()['cnt'];
    $students_evaluated = $conn->query("SELECT COUNT(DISTINCT e.student_id) as cnt FROM evaluation_responses er JOIN evaluations e ON er.evaluation_id = e.evaluation_id WHERE $sy_cond")->fetch_assoc()['cnt'];
    $total_teachers = $conn->query("SELECT COUNT(DISTINCT e.teacher_id) as cnt FROM evaluations e WHERE $sy_cond")->fetch_assoc()['cnt'];
    $avg_rating = $conn->query("SELECT AVG(er.response) as avg FROM evaluation_responses er JOIN evaluations e ON er.evaluation_id = e.evaluation_id WHERE $sy_cond")->fetch_assoc()['avg'];

    // Student population for participation rate (same denominator idea as data_analytics.php)
    if ($selected_year === 'all') {
        $total_students_sql = "SELECT COUNT(DISTINCT s.student_id) as total_students FROM students s";
    } else {
        $yearEsc = $conn->real_escape_string(analytics_normalize_school_year((string) $selected_year));
        $total_students_sql = "SELECT COUNT(DISTINCT s.student_id) as total_students FROM students s WHERE REPLACE(REPLACE(s.school_year, '–', '-'), '—', '-') = '$yearEsc'";
    }
    $total_students_row = $conn->query($total_students_sql);
    $total_students = $total_students_row ? (int) ($total_students_row->fetch_assoc()['total_students'] ?? 0) : 0;
    $participation_rate = $total_students > 0 ? round(($students_evaluated / $total_students) * 100, 1) : 0;
    
    $summary['overall'] = [
        'total_evaluations' => $total_eval,
        'students_evaluated' => $students_evaluated,
        'total_students' => $total_students,
        'total_teachers' => $total_teachers,
        'avg_rating' => round($avg_rating, 2),
        'school_year' => $school_year_label,
        'semester' => $semester_label,
        'generated_date' => date('Y-m-d H:i:s')
    ];
    
    // Rating Distribution
    $rating_dist_sql = "
        SELECT 
            CASE 
                WHEN er.response >= 4.5 THEN 'Excellent (4.5-5.0)'
                WHEN er.response >= 3.5 THEN 'Good (3.5-4.4)'
                WHEN er.response >= 2.5 THEN 'Average (2.5-3.4)'
                WHEN er.response >= 1.5 THEN 'Below Average (1.5-2.4)'
                ELSE 'Poor (1.0-1.4)'
            END as rating_category,
            COUNT(*) as count,
            ROUND(COUNT(*) / (SELECT COUNT(*) FROM evaluation_responses er2 JOIN evaluations e ON er2.evaluation_id = e.evaluation_id WHERE $sy_cond) * 100, 1) as percentage
        FROM evaluation_responses er
        JOIN evaluations e ON er.evaluation_id = e.evaluation_id
        WHERE $sy_cond
        GROUP BY rating_category
        ORDER BY FIELD(rating_category, 'Excellent (4.5-5.0)', 'Good (3.5-4.4)', 'Average (2.5-3.4)', 'Below Average (1.5-2.4)', 'Poor (1.0-1.4)')";
    
    $rating_result = $conn->query($rating_dist_sql);
    $summary['rating_distribution'] = [];
    while ($row = $rating_result->fetch_assoc()) {
        $summary['rating_distribution'][] = $row;
    }
    
    $summary['participation_rate'] = $participation_rate;
    
    // Top Performing Teachers
    $top_sql = "
        SELECT 
            CONCAT(u.first_name, ' ', u.last_name) as name,
            s.subject_name,
            AVG(er.response) as rating,
            COUNT(DISTINCT e.evaluation_id) as eval_count
        FROM evaluation_responses er
        JOIN evaluations e ON er.evaluation_id = e.evaluation_id
        JOIN teachers t ON e.teacher_id = t.teacher_id
        JOIN users u ON t.user_id = u.user_id
        JOIN subjects s ON e.subject_id = s.subject_id
        WHERE $sy_cond
        GROUP BY e.teacher_id, s.subject_id
        ORDER BY rating DESC
        LIMIT 10";
    
    $top_result = $conn->query($top_sql);
    $summary['top_teachers'] = [];
    while ($row = $top_result->fetch_assoc()) {
        $summary['top_teachers'][] = $row;
    }
    
    // Lowest Performing Teachers
    $low_sql = "
        SELECT 
            CONCAT(u.first_name, ' ', u.last_name) as name,
            s.subject_name,
            AVG(er.response) as rating,
            COUNT(DISTINCT e.evaluation_id) as eval_count
        FROM evaluation_responses er
        JOIN evaluations e ON er.evaluation_id = e.evaluation_id
        JOIN teachers t ON e.teacher_id = t.teacher_id
        JOIN users u ON t.user_id = u.user_id
        JOIN subjects s ON e.subject_id = s.subject_id
        WHERE $sy_cond
        GROUP BY e.teacher_id, s.subject_id
        ORDER BY rating ASC
        LIMIT 10";
    
    $low_result = $conn->query($low_sql);
    $summary['lowest_teachers'] = [];
    while ($row = $low_result->fetch_assoc()) {
        $summary['lowest_teachers'][] = $row;
    }
    
    // Category Performance (Strand-wise Analysis)
    $category_sql = "
        SELECT 
            COALESCE(ec.category_name, CONCAT('Category #', COALESCE(eq.category_id, 0))) as category_name,
            AVG(er.response) as avg_score,
            COUNT(*) as response_count,
            STDDEV(er.response) as std_dev,
            COUNT(CASE WHEN er.response >= 4.5 THEN 1 END) as excellent_count,
            COUNT(CASE WHEN er.response >= 3.5 AND er.response < 4.5 THEN 1 END) as good_count,
            COUNT(CASE WHEN er.response < 2.5 THEN 1 END) as critical_count
        FROM evaluation_responses er
        JOIN evaluations e ON er.evaluation_id = e.evaluation_id
        LEFT JOIN evaluation_questions eq ON er.question_id = eq.question_id
        LEFT JOIN evaluation_categories ec ON eq.category_id = ec.category_id
        WHERE $sy_cond
        GROUP BY eq.category_id, ec.category_name
        ORDER BY avg_score DESC";
    
    $category_result = $conn->query($category_sql);
    $summary['categories'] = [];
    $critical_categories = [];
    $strong_categories = [];
    
    while ($row = $category_result->fetch_assoc()) {
        $summary['categories'][] = $row;
        if ($row['avg_score'] < 2.5) {
            $critical_categories[] = [
                'name' => $row['category_name'],
                'score' => $row['avg_score']
            ];
        }
        if ($row['avg_score'] >= 4.0) {
            $strong_categories[] = [
                'name' => $row['category_name'],
                'score' => $row['avg_score']
            ];
        }
    }
    $summary['critical_categories'] = $critical_categories;
    $summary['strong_categories'] = $strong_categories;
    
    // Strand-wise Performance
    $strand_sql = "
        SELECT 
            s.strand,
            COUNT(DISTINCT e.student_id) as unique_students,
            AVG(er.response) as avg_rating,
            COUNT(*) as total_evaluations
        FROM evaluation_responses er
        JOIN evaluations e ON er.evaluation_id = e.evaluation_id
        JOIN subjects s ON e.subject_id = s.subject_id
        WHERE $sy_cond
        GROUP BY s.strand
        ORDER BY avg_rating DESC";
    
    $strand_result = $conn->query($strand_sql);
    $summary['strands'] = [];
    while ($row = $strand_result->fetch_assoc()) {
        $summary['strands'][] = $row;
    }
    
    // Early Warning System - Low Performing Teachers with Issues
    $warning_sql = "
        SELECT 
            CONCAT(u.first_name, ' ', u.last_name) as teacher_name,
            s.subject_name,
            AVG(er.response) as avg_rating,
            COUNT(DISTINCT e.evaluation_id) as eval_count,
            STDDEV(er.response) as rating_std_dev
        FROM evaluation_responses er
        JOIN evaluations e ON er.evaluation_id = e.evaluation_id
        JOIN teachers t ON e.teacher_id = t.teacher_id
        JOIN users u ON t.user_id = u.user_id
        JOIN subjects s ON e.subject_id = s.subject_id
        WHERE $sy_cond
        GROUP BY e.teacher_id, s.subject_id
        HAVING eval_count >= 3 AND avg_rating < 3.0
        ORDER BY avg_rating ASC
        LIMIT 10";
    
    $warning_result = $conn->query($warning_sql);
    $summary['early_warnings'] = [];
    while ($row = $warning_result->fetch_assoc()) {
        $summary['early_warnings'][] = $row;
    }
    
    return $summary;
}

// ============================================
// HELPER: Generate PDF
// ============================================
function generate_pdf_report($summary, $username) {
    // Some TCPDF installs (e.g., via Composer) may not define the PDF_* config constants.
    // Fall back to TCPDF defaults to avoid fatals.
    $pageOrientation = defined('PDF_PAGE_ORIENTATION') ? PDF_PAGE_ORIENTATION : 'P';
    $pageUnit        = defined('PDF_PAGE_UNIT') ? PDF_PAGE_UNIT : 'mm';
    $pageFormat      = defined('PDF_PAGE_FORMAT') ? PDF_PAGE_FORMAT : 'A4';

    $pdf = new \TCPDF($pageOrientation, $pageUnit, $pageFormat, true, 'UTF-8', false);
    
    // Set document properties
    $pdf->SetCreator('Analytics System');
    $pdf->SetAuthor($username);
    $pdf->SetTitle('Faculty Evaluation Summary Report');
    $pdf->SetSubject('Comprehensive Analytics Summary Report');
    
    // Set margins
    $pdf->SetMargins(15, 20, 15);
    $pdf->SetAutoPageBreak(TRUE, 15);
    
    // Add first page
    $pdf->AddPage();
    
    // ===== COVER PAGE =====
    $pdf->SetFont('helvetica', '', 11);
    
    // Title with styling
    $pdf->SetFont('helvetica', 'B', 28);
    $pdf->SetTextColor(128, 0, 0);
    $pdf->Cell(0, 20, 'Faculty Evaluation Report', 0, 1, 'C');
    
    $pdf->SetFont('helvetica', 'I', 12);
    $pdf->SetTextColor(100, 100, 100);
    $pdf->Cell(0, 10, 'Comprehensive Analytics & Insights', 0, 1, 'C');
    $pdf->Ln(15);
    
    // Report Metadata
    $pdf->SetFont('helvetica', '', 10);
    $pdf->SetTextColor(0, 0, 0);
    
    $metadata = [
        'School Year' => $summary['overall']['school_year'],
        'Semester' => $summary['overall']['semester'],
        'Report Generated' => $summary['overall']['generated_date'],
        'Generated By' => htmlspecialchars($username),
        'Report Type' => 'Professional Analytics Summary'
    ];
    
    foreach ($metadata as $key => $value) {
        $pdf->SetFont('helvetica', 'B', 10);
        $pdf->Cell(50, 8, $key . ':', 0, 0);
        $pdf->SetFont('helvetica', '', 10);
        $pdf->Cell(0, 8, $value, 0, 1);
    }
    
    $pdf->Ln(20);
    
    // Key Metrics Summary Box
    $pdf->SetFillColor(240, 240, 240);
    $pdf->SetFont('helvetica', 'B', 12);
    $pdf->SetTextColor(128, 0, 0);
    $pdf->Cell(0, 8, 'KEY METRICS OVERVIEW', 0, 1, 'L', true);
    
    $pdf->SetFont('helvetica', '', 10);
    $pdf->SetTextColor(0, 0, 0);
    
    $metrics_data = [
        'Total Evaluations' => $summary['overall']['total_evaluations'],
        'Teachers Evaluated' => $summary['overall']['total_teachers'],
        'Students Participating' => $summary['overall']['students_evaluated'],
        'Overall Average Rating' => $summary['overall']['avg_rating'] . '/5.0'
    ];
    
    foreach ($metrics_data as $metric => $value) {
        $pdf->Cell(80, 7, $metric . ':', 0, 0);
        $pdf->SetFont('helvetica', 'B', 10);
        $pdf->Cell(0, 7, $value, 0, 1);
        $pdf->SetFont('helvetica', '', 10);
    }
    
    $pdf->Ln(10);
    
    // Page break for content
    $pdf->AddPage();
    
    // ===== SECTION 1: EXECUTIVE SUMMARY =====
    $pdf->SetFont('helvetica', 'B', 14);
    $pdf->SetTextColor(128, 0, 0);
    $pdf->Cell(0, 10, '1. EXECUTIVE SUMMARY', 0, 1, 'L');
    $pdf->Ln(3);
    
    // Overall Rating Analysis
    $rating_interpretation = '';
    $avg = $summary['overall']['avg_rating'];
    if ($avg >= 4.5) {
        $rating_interpretation = 'Excellent: Outstanding performance across the faculty';
    } elseif ($avg >= 4.0) {
        $rating_interpretation = 'Very Good: Strong overall performance with minor improvement areas';
    } elseif ($avg >= 3.5) {
        $rating_interpretation = 'Good: Satisfactory performance; targeted development recommended';
    } elseif ($avg >= 3.0) {
        $rating_interpretation = 'Adequate: Performance is acceptable but improvement needed';
    } else {
        $rating_interpretation = 'Below Standard: Comprehensive intervention required';
    }
    
    $pdf->SetFont('helvetica', '', 10);
    $pdf->SetTextColor(0, 0, 0);
    $pdf->MultiCell(0, 6, 'Overall Assessment: ' . $rating_interpretation, 0, 'L');
    $pdf->Ln(5);
    
    // Rating Distribution Summary
    $pdf->SetFont('helvetica', 'B', 10);
    $pdf->Cell(0, 8, 'Rating Distribution Breakdown:', 0, 1, 'L');
    
    $pdf->SetFont('helvetica', '', 9);
    $html = '<table cellpadding="4" cellspacing="0" border="1" style="border-collapse: collapse;">
        <tr style="background-color: #f0f0f0;">
            <th width="45%"><b>Category</b></th>
            <th width="25%"><b>Count</b></th>
            <th width="30%"><b>Percentage</b></th>
        </tr>';
    
    foreach ($summary['rating_distribution'] as $rating) {
        $html .= '<tr>
            <td>' . htmlspecialchars($rating['rating_category']) . '</td>
            <td align="center">' . $rating['count'] . '</td>
            <td align="center">' . $rating['percentage'] . '%</td>
        </tr>';
    }
    
    $html .= '</table>';
    $pdf->writeHTML($html, true, false, true, false, '');
    $pdf->Ln(5);
    
    // ===== SECTION 2: CATEGORY PERFORMANCE =====
    $pdf->SetFont('helvetica', 'B', 14);
    $pdf->SetTextColor(128, 0, 0);
    $pdf->Cell(0, 10, '2. CATEGORY PERFORMANCE ANALYSIS', 0, 1, 'L');
    $pdf->Ln(3);
    
    // Highlight Critical Categories
    if (!empty($summary['critical_categories'])) {
        $pdf->SetFont('helvetica', 'B', 10);
        $pdf->SetTextColor(220, 53, 69);
        $pdf->Cell(0, 8, 'CRITICAL AREAS (Score < 2.5):', 0, 1, 'L');
        
        $pdf->SetFont('helvetica', '', 9);
        $pdf->SetTextColor(0, 0, 0);
        foreach ($summary['critical_categories'] as $cat) {
            $pdf->Cell(10, 6, '', 0, 0);
            $pdf->Cell(0, 6, '• ' . htmlspecialchars($cat['name']) . ' - ' . round($cat['score'], 2) . '/5.0 (URGENT ATTENTION NEEDED)', 0, 1);
        }
        $pdf->Ln(2);
    }
    
    // Highlight Strong Categories
    if (!empty($summary['strong_categories'])) {
        $pdf->SetFont('helvetica', 'B', 10);
        $pdf->SetTextColor(40, 167, 69);
        $pdf->Cell(0, 8, 'STRENGTHS (Score >= 4.0):', 0, 1, 'L');
        
        $pdf->SetFont('helvetica', '', 9);
        $pdf->SetTextColor(0, 0, 0);
        foreach ($summary['strong_categories'] as $cat) {
            $pdf->Cell(10, 6, '', 0, 0);
            $pdf->Cell(0, 6, '• ' . htmlspecialchars($cat['name']) . ' - ' . round($cat['score'], 2) . '/5.0', 0, 1);
        }
        $pdf->Ln(2);
    }
    
    // Full Category Table
    $pdf->SetFont('helvetica', 'B', 10);
    $pdf->SetTextColor(128, 0, 0);
    $pdf->Cell(0, 8, 'All Categories Ranked by Performance:', 0, 1, 'L');
    
    $pdf->SetFont('helvetica', '', 8);
    $pdf->SetTextColor(0, 0, 0);
    
    $html = '<table cellpadding="4" cellspacing="0" border="1" style="border-collapse: collapse;">
        <tr style="background-color: #f0f0f0;">
            <th width="50%"><b>Category</b></th>
            <th width="15%"><b>Avg Score</b></th>
            <th width="15%"><b>Responses</b></th>
            <th width="20%"><b>Status</b></th>
        </tr>';
    
    foreach ($summary['categories'] as $cat) {
        $status = '';
        if ($cat['avg_score'] >= 4.0) {
            $status = 'Excellent';
        } elseif ($cat['avg_score'] >= 3.0) {
            $status = 'Good';
        } elseif ($cat['avg_score'] >= 2.5) {
            $status = 'Fair';
        } else {
            $status = 'Critical';
        }
        
        $html .= '<tr>
            <td>' . htmlspecialchars($cat['category_name']) . '</td>
            <td align="center"><b>' . round($cat['avg_score'], 2) . '</b>/5.0</td>
            <td align="center">' . $cat['response_count'] . '</td>
            <td align="center">' . $status . '</td>
        </tr>';
    }
    
    $html .= '</table>';
    $pdf->writeHTML($html, true, false, true, false, '');
    $pdf->Ln(5);
    
    // New Page for Teacher Performance
    $pdf->AddPage();
    
    // ===== SECTION 3: STRAND PERFORMANCE =====
    if (!empty($summary['strands'])) {
        $pdf->SetFont('helvetica', 'B', 14);
        $pdf->SetTextColor(128, 0, 0);
        $pdf->Cell(0, 10, '3. STRAND-WISE PERFORMANCE', 0, 1, 'L');
        $pdf->Ln(3);
        
        $pdf->SetFont('helvetica', '', 9);
        $pdf->SetTextColor(0, 0, 0);
        
        $html = '<table cellpadding="4" cellspacing="0" border="1" style="border-collapse: collapse;">
            <tr style="background-color: #f0f0f0;">
                <th width="30%"><b>Strand</b></th>
                <th width="20%"><b>Avg Rating</b></th>
                <th width="25%"><b>Students</b></th>
                <th width="25%"><b>Evaluations</b></th>
            </tr>';
        
        foreach ($summary['strands'] as $strand) {
            $html .= '<tr>
                <td>' . htmlspecialchars($strand['strand']) . '</td>
                <td align="center"><b>' . round($strand['avg_rating'], 2) . '</b>/5.0</td>
                <td align="center">' . $strand['unique_students'] . '</td>
                <td align="center">' . $strand['total_evaluations'] . '</td>
            </tr>';
        }
        
        $html .= '</table>';
        $pdf->writeHTML($html, true, false, true, false, '');
        $pdf->Ln(5);
    }
    
    // ===== SECTION 4: TOP PERFORMING TEACHERS =====
    $pdf->SetFont('helvetica', 'B', 14);
    $pdf->SetTextColor(128, 0, 0);
    $pdf->Cell(0, 10, '4. EXCELLENCE IN TEACHING', 0, 1, 'L');
    $pdf->Ln(3);
    
    $pdf->SetFont('helvetica', '', 9);
    $pdf->SetTextColor(0, 0, 0);
    
    $html = '<table cellpadding="4" cellspacing="0" border="1" style="border-collapse: collapse;">
        <tr style="background-color: #f0f0f0;">
            <th width="35%"><b>Teacher Name</b></th>
            <th width="30%"><b>Subject</b></th>
            <th width="20%"><b>Rating</b></th>
            <th width="15%"><b>Evals</b></th>
        </tr>';
    
